create table if not exists public.confirmation_tokens (
  token_hash text primary key,
  subject_type text not null check (subject_type in ('registration', 'company_registration')),
  subject_id uuid not null,
  expires_at timestamptz not null,
  revoked_at timestamptz,
  created_at timestamptz not null default now(),
  last_used_at timestamptz,
  constraint confirmation_tokens_hash_format check (token_hash ~ '^[a-f0-9]{64}$')
);
create index if not exists confirmation_tokens_subject_idx
  on public.confirmation_tokens (subject_type, subject_id, created_at desc);
create index if not exists confirmation_tokens_expiry_idx
  on public.confirmation_tokens (expires_at) where revoked_at is null;

