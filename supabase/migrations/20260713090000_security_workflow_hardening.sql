  nonce_hash text primary key,
  purpose text not null,
  expires_at timestamptz not null,
  consumed_at timestamptz not null default now(),
  constraint form_submission_nonces_hash_format check (nonce_hash ~ '^[a-f0-9]{64}$')
);

create table if not exists public.form_rate_limits (
  scope text not null,
  identity_hash text not null,
  window_started_at timestamptz not null default now(),
  attempt_count integer not null default 0 check (attempt_count >= 0),
  blocked_until timestamptz,
  updated_at timestamptz not null default now(),
  primary key (scope, identity_hash),
  constraint form_rate_limits_hash_format check (identity_hash ~ '^[a-f0-9]{64}$')
);
create index if not exists form_rate_limits_updated_idx on public.form_rate_limits (updated_at);

