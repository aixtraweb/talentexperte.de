create or replace function public.dashboard_delete_registration(
  p_table text,
  p_registration_id uuid
)
returns boolean
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  deleted_count integer;
begin
  if not public.is_dashboard_admin() then
    raise exception using errcode = '42501', message = 'DASHBOARD_ADMIN_REQUIRED';
  end if;
  if p_table not in ('anmeldungen', 'firmen_anmeldungen') then
    raise exception using errcode = '22023', message = 'REGISTRATION_TABLE_INVALID';
  end if;
  delete from public.teilnahme where referenz_id = p_registration_id;
  if p_table = 'anmeldungen' then
    delete from public.anmeldungen where id = p_registration_id;
  else
    delete from public.firmen_anmeldungen where id = p_registration_id;
  end if;
  get diagnostics deleted_count = row_count;
  return deleted_count = 1;
end;
$$;
revoke all on function public.dashboard_delete_registration(text, uuid) from public, anon;
grant execute on function public.dashboard_delete_registration(text, uuid) to authenticated, service_role;
