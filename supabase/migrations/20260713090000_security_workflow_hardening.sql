create or replace function public.audit_sensitive_change()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public, auth
as $$
declare
  claims jsonb := coalesce(nullif(current_setting('request.jwt.claims', true), ''), '{}')::jsonb;
  old_row jsonb := case when tg_op in ('UPDATE', 'DELETE') then to_jsonb(old) else null end;
  new_row jsonb := case when tg_op in ('INSERT', 'UPDATE') then to_jsonb(new) else null end;
begin
  insert into public.security_audit_log (
    table_name, record_id, action, actor_user_id, actor_email, old_data, new_data
  ) values (
    tg_table_name,
    coalesce(new_row ->> 'id', old_row ->> 'id'),
    tg_op,
    nullif(claims ->> 'sub', '')::uuid,
    lower(nullif(claims ->> 'email', '')),
    old_row,
    new_row
  );
  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;

