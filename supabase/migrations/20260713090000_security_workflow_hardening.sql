create or replace function public.guard_anmeldung_booking()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  camp_row record;
  occupied integer;
begin
  if tg_op = 'UPDATE' and new.camp_id = old.camp_id
    and coalesce(old.zahlungsstatus, 'offen') not in ('storniert', 'erstattet') then
    return new;
  end if;
  if coalesce(new.zahlungsstatus, 'offen') in ('storniert', 'erstattet') then return new; end if;
  perform pg_advisory_xact_lock(hashtextextended(new.camp_id::text, 0));
  select id, status, max_plaetze, datum_bis into camp_row
    from public.camps where id = new.camp_id for update;
  if not found or camp_row.status <> 'aktiv' or camp_row.datum_bis < current_date then
    raise exception using errcode = 'P0001', message = 'CAMP_NOT_BOOKABLE';
  end if;
  if exists (
    select 1 from public.anmeldungen a where a.camp_id = new.camp_id
      and lower(a.vorname) = lower(new.vorname) and lower(a.nachname) = lower(new.nachname)
      and lower(a.email) = lower(new.email)
      and coalesce(a.zahlungsstatus, 'offen') not in ('storniert', 'erstattet')
      and (tg_op <> 'UPDATE' or a.id <> new.id)
  ) then raise exception using errcode = '23505', message = 'REGISTRATION_DUPLICATE'; end if;
  select
    (select count(*) from public.anmeldungen a where a.camp_id = new.camp_id
      and coalesce(a.payer_type, 'parent') <> 'company'
      and coalesce(a.zahlungsstatus, 'offen') not in ('storniert', 'erstattet')
      and (tg_op <> 'UPDATE' or a.id <> new.id))
    +
    (select count(*) from public.firmen_anmeldungen f where f.camp_id = new.camp_id
      and coalesce(f.status, 'bezahlt') not in ('storniert', 'erstattet'))
  into occupied;
  if occupied >= camp_row.max_plaetze then
    raise exception using errcode = 'P0001', message = 'CAMP_FULL';
  end if;
  return new;
end;
$$;

create or replace function public.guard_company_booking()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  camp_row record;
  occupied integer;
begin
  if tg_op = 'UPDATE' and new.camp_id = old.camp_id
    and coalesce(old.status, 'bezahlt') not in ('storniert', 'erstattet') then return new; end if;
  if coalesce(new.status, 'bezahlt') in ('storniert', 'erstattet') then return new; end if;
  perform pg_advisory_xact_lock(hashtextextended(new.camp_id::text, 0));
  select id, status, max_plaetze, datum_bis into camp_row
    from public.camps where id = new.camp_id for update;
  if not found or camp_row.status <> 'aktiv' or camp_row.datum_bis < current_date then
    raise exception using errcode = 'P0001', message = 'CAMP_NOT_BOOKABLE';
  end if;
  if exists (
    select 1 from public.firmen_anmeldungen f where f.camp_id = new.camp_id
      and lower(f.kind_vorname) = lower(new.kind_vorname)
      and lower(f.kind_nachname) = lower(new.kind_nachname)
      and coalesce(lower(f.mitarbeiter_email), '') = coalesce(lower(new.mitarbeiter_email), '')
      and coalesce(f.status, 'bezahlt') not in ('storniert', 'erstattet')
      and (tg_op <> 'UPDATE' or f.id <> new.id)
  ) then raise exception using errcode = '23505', message = 'REGISTRATION_DUPLICATE'; end if;
  select
    (select count(*) from public.anmeldungen a where a.camp_id = new.camp_id
      and coalesce(a.payer_type, 'parent') <> 'company'
      and coalesce(a.zahlungsstatus, 'offen') not in ('storniert', 'erstattet'))
    +
    (select count(*) from public.firmen_anmeldungen f where f.camp_id = new.camp_id
      and coalesce(f.status, 'bezahlt') not in ('storniert', 'erstattet')
      and (tg_op <> 'UPDATE' or f.id <> new.id))
  into occupied;
  if occupied >= camp_row.max_plaetze then
    raise exception using errcode = 'P0001', message = 'CAMP_FULL';
  end if;
  return new;
end;
$$;

