create or replace function public.consume_form_nonce(
  p_nonce_hash text,
  p_purpose text,
  p_expires_at timestamptz
)
returns boolean
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  inserted_count integer;
begin
  if p_nonce_hash !~ '^[a-f0-9]{64}$' or btrim(p_purpose) = ''
    or p_expires_at <= now() or p_expires_at > now() + interval '3 hours' then
    return false;
  end if;
  delete from public.form_submission_nonces where expires_at < now() - interval '1 day';
  insert into public.form_submission_nonces (nonce_hash, purpose, expires_at)
  values (p_nonce_hash, p_purpose, p_expires_at)
  on conflict do nothing;
  get diagnostics inserted_count = row_count;
  return inserted_count = 1;
end;
$$;

create or replace function public.consume_form_rate_limit(
  p_scope text,
  p_identity_hash text,
  p_limit integer,
  p_window_seconds integer
)
returns boolean
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  state public.form_rate_limits%rowtype;
  window_interval interval;
begin
  if btrim(p_scope) = '' or p_identity_hash !~ '^[a-f0-9]{64}$'
    or p_limit < 1 or p_window_seconds < 10 or p_window_seconds > 86400 then
    return false;
  end if;
  window_interval := make_interval(secs => p_window_seconds);
  delete from public.form_rate_limits where updated_at < now() - interval '7 days';
  insert into public.form_rate_limits (scope, identity_hash)
  values (p_scope, p_identity_hash) on conflict do nothing;
  select * into state from public.form_rate_limits
    where scope = p_scope and identity_hash = p_identity_hash for update;
  if state.blocked_until is not null and state.blocked_until > now() then
    return false;
  end if;
  if state.window_started_at <= now() - window_interval then
    state.window_started_at := now();
    state.attempt_count := 0;
  end if;
  state.attempt_count := state.attempt_count + 1;
  update public.form_rate_limits set
    window_started_at = state.window_started_at,
    attempt_count = state.attempt_count,
    blocked_until = case when state.attempt_count > p_limit then now() + window_interval else null end,
    updated_at = now()
  where scope = p_scope and identity_hash = p_identity_hash;
  return state.attempt_count <= p_limit;
end;
$$;

revoke all on function public.consume_form_nonce(text, text, timestamptz) from public, anon, authenticated;
